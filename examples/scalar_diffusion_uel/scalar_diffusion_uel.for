      SUBROUTINE heatdiffusionmaterial_stress_PK1(F, T, props, P_out)
      IMPLICIT NONE
      DOUBLE COMPLEX, INTENT(IN) :: F(3,3)
      DOUBLE COMPLEX, INTENT(IN) :: T
      DOUBLE PRECISION, INTENT(IN) :: props(5)
      DOUBLE COMPLEX, INTENT(OUT) :: P_out(3,3)

      DOUBLE COMPLEX :: det33z
      DOUBLE COMPLEX :: INV1(3,3)
      DOUBLE COMPLEX :: AT2(3,3)
      DOUBLE COMPLEX :: finv_t(3,3)
      DOUBLE COMPLEX :: P_mech(3,3)
      DOUBLE COMPLEX :: P_thermal(3,3)
      DOUBLE COMPLEX :: J
      INTEGER :: ii, jj

      J = det33z(F)
      CALL inv33z(F, INV1)
      CALL transpose33z(INV1, AT2)
      finv_t = AT2
      P_mech = ((DCMPLX(props(1), 0.0d0) * (F - finv_t)) +
     &((DCMPLX(props(2), 0.0d0) * LOG(J)) * finv_t))
      P_thermal = ((((-DCMPLX(props(2), 0.0d0)) * DCMPLX(props(3),
     &0.0d0)) * T) * finv_t)

      DO ii = 1, 3
        DO jj = 1, 3
          P_out(ii,jj) = (P_mech(ii,jj) + P_thermal(ii,jj))
        END DO
      END DO

      RETURN
      END SUBROUTINE heatdiffusionmaterial_stress_PK1

