C     --- Inputs (all DOUBLE PRECISION) ---
      DOUBLE PRECISION, INTENT(IN) :: F(3,3)
      DOUBLE PRECISION, INTENT(IN) :: T
      DOUBLE PRECISION, INTENT(IN) :: grad_T(3)
      DOUBLE PRECISION, INTENT(IN) :: F_old(3,3)
      DOUBLE PRECISION, INTENT(IN) :: T_old
      DOUBLE PRECISION, INTENT(IN) :: props(5)
      DOUBLE PRECISION, INTENT(IN) :: dt

