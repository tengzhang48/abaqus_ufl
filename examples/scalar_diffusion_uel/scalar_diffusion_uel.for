      DOUBLE PRECISION, INTENT(OUT) :: dPK1_dT(3,3)
      DOUBLE PRECISION, INTENT(OUT) :: dflux_dF(3,3,3)
      DOUBLE PRECISION, INTENT(OUT) :: dflux_dT(3)
      DOUBLE PRECISION, INTENT(OUT) :: dflux_dgrad_T(3,3)
      DOUBLE PRECISION, INTENT(OUT) :: dstorage_dF(3,3)
      DOUBLE PRECISION, INTENT(OUT) :: dstorage_dT

C     CS_H = 1e-10: verified identical to 1e-30 for this model.
C     Complex-step has no subtractive cancellation, so any
C     small h gives machine-precision tangents.
      DOUBLE PRECISION, PARAMETER :: CS_H = 1.0d-10
      DOUBLE COMPLEX :: Fz(3,3), F_old_z(3,3)
      DOUBLE COMPLEX :: Tz
      DOUBLE COMPLEX :: grad_T_z(3)
      DOUBLE COMPLEX :: T_old_z

      DOUBLE COMPLEX :: PKz(3,3), rpz, jRz(3), cdotz
      INTEGER :: i, j, k, l

C     Convert history variables (real, not perturbed)
      CALL real2complex33(F_old, F_old_z)
      T_old_z = DCMPLX(T_old, 0.0d0)

C     === dPK1_dF: d(stress_PK1)/d(F) ===
      DO k = 1, 3
        DO l = 1, 3
          CALL real2complex33(F, Fz)
          Tz = DCMPLX(T, 0.0d0)
          CALL real2complex3(grad_T, grad_T_z)
          Fz(k,l) = Fz(k,l) + DCMPLX(0.0d0, CS_H)
          CALL heatdiffusionmaterial_stress_PK1(Fz, Tz, props, PKz)
          DO i = 1, 3
            DO j = 1, 3
              dPK1_dF(i,j,k,l) = AIMAG(PKz(i,j))/CS_H
            END DO
          END DO
        END DO
      END DO

C     === dPK1_dT: d(stress_PK1)/d(T) ===
      CALL real2complex33(F, Fz)
      Tz = DCMPLX(T, CS_H)
      CALL real2complex3(grad_T, grad_T_z)
      CALL heatdiffusionmaterial_stress_PK1(Fz, Tz, props, PKz)
      DO i = 1, 3
        DO j = 1, 3
          dPK1_dT(i,j) = AIMAG(PKz(i,j)) / CS_H
        END DO
      END DO

C     === dflux_dF: d(solvent_flux)/d(F) ===
      DO k = 1, 3
        DO l = 1, 3
          CALL real2complex33(F, Fz)
          Tz = DCMPLX(T, 0.0d0)
          CALL real2complex3(grad_T, grad_T_z)
          Fz(k,l) = Fz(k,l) + DCMPLX(0.0d0, CS_H)
          CALL heatdiffusionmaterial_solvent_flux(Fz, Tz, grad_T_z,
     &props, jRz)
          DO i = 1, 3
            dflux_dF(i,k,l) = AIMAG(jRz(i)) / CS_H
          END DO
        END DO
      END DO

C     === dflux_dT: d(solvent_flux)/d(T) ===
      CALL real2complex33(F, Fz)
      Tz = DCMPLX(T, CS_H)
      CALL real2complex3(grad_T, grad_T_z)
      CALL heatdiffusionmaterial_solvent_flux(Fz, Tz, grad_T_z, props,
     &jRz)
      DO i = 1, 3
        dflux_dT(i) = AIMAG(jRz(i)) / CS_H
      END DO

C     === dflux_dgrad_T: d(solvent_flux)/d(grad_T) ===
      DO k = 1, 3
        CALL real2complex33(F, Fz)
        Tz = DCMPLX(T, 0.0d0)
        CALL real2complex3(grad_T, grad_T_z)
        grad_T_z(k) = grad_T_z(k) + DCMPLX(0.0d0, CS_H)
        CALL heatdiffusionmaterial_solvent_flux(Fz, Tz, grad_T_z, props,
     & jRz)
        DO i = 1, 3
          dflux_dgrad_T(i,k) = AIMAG(jRz(i)) / CS_H
        END DO
      END DO

C     === dstorage_dF: d(solvent_storage)/d(F) ===
      DO k = 1, 3
        DO l = 1, 3
          CALL real2complex33(F, Fz)
          Tz = DCMPLX(T, 0.0d0)
          CALL real2complex3(grad_T, grad_T_z)
          Fz(k,l) = Fz(k,l) + DCMPLX(0.0d0, CS_H)
          CALL heatdiffusionmaterial_solvent_storage(Fz, F_old_z, Tz,
     &T_old_z, dt, props, cdotz)
          dstorage_dF(k,l) = AIMAG(cdotz) / CS_H
        END DO
      END DO

C     === dstorage_dT: d(solvent_storage)/d(T) ===
      CALL real2complex33(F, Fz)
      Tz = DCMPLX(T, CS_H)
      CALL real2complex3(grad_T, grad_T_z)
      CALL heatdiffusionmaterial_solvent_storage(Fz, F_old_z, Tz,
     &T_old_z, dt, props, cdotz)
      dstorage_dT = AIMAG(cdotz) / CS_H

