      SUBROUTINE smallstrainviscoelastic_stress_update(sigma_old,
     &strain_old, dstrain, eps_v_old, dt, cutback_flag, props,
     &sigma_new, eps_v_new)
      IMPLICIT NONE
      DOUBLE COMPLEX, INTENT(IN)  :: sigma_old(3,3)
      DOUBLE COMPLEX, INTENT(IN)  :: strain_old(3,3)
      DOUBLE COMPLEX, INTENT(IN)  :: dstrain(3,3)
      DOUBLE COMPLEX, INTENT(IN)  :: eps_v_old(3,3)
      DOUBLE PRECISION, INTENT(IN) :: dt
      DOUBLE COMPLEX, INTENT(OUT) :: cutback_flag
      DOUBLE PRECISION, INTENT(IN) :: props(4)
      DOUBLE COMPLEX, INTENT(OUT) :: sigma_new(3,3)
      DOUBLE COMPLEX, INTENT(OUT) :: eps_v_new(3,3)

      DOUBLE COMPLEX :: det33z
      DOUBLE COMPLEX :: cs_sin
      DOUBLE COMPLEX :: cs_cos
      DOUBLE COMPLEX :: cs_tan
      DOUBLE COMPLEX :: cs_sinh
      DOUBLE COMPLEX :: cs_cosh
      DOUBLE COMPLEX :: cs_tanh
      DOUBLE COMPLEX :: cs_atan
      DOUBLE COMPLEX :: cs_acos
      DOUBLE COMPLEX :: cs_erf
      DOUBLE COMPLEX :: cs_erfc
      DOUBLE COMPLEX :: EYE1(3,3)
      DOUBLE COMPLEX :: I(3,3)
      DOUBLE COMPLEX :: strain_new(3,3)
      DOUBLE COMPLEX :: dev_e(3,3)
      DOUBLE COMPLEX :: ratio
      INTEGER :: ii, jj

      cutback_flag = DCMPLX(0.0d0, 0.0d0)

      CALL eye33z(EYE1)
      I = EYE1
      strain_new = (strain_old + dstrain)
      ratio = (dt / DCMPLX(props(4), 0.0d0))
      dev_e = (strain_new - (((DCMPLX(1.000000000000000d+00, 0.0d0) /
     &DCMPLX(3.000000000000000d+00, 0.0d0)) * (strain_new(1,1)+
     &strain_new(2,2)+strain_new(3,3))) * I))
      eps_v_new = ((eps_v_old + (ratio * dev_e)) /
     &(DCMPLX(1.000000000000000d+00, 0.0d0) + ratio))
      sigma_new = ((((DCMPLX(props(1), 0.0d0) * (strain_new(1,1)+
     &strain_new(2,2)+strain_new(3,3))) * I) +
     &((DCMPLX(2.000000000000000d+00, 0.0d0) * DCMPLX(props(2), 0.0d0))
     &* dev_e)) + ((DCMPLX(2.000000000000000d+00, 0.0d0) *
     &DCMPLX(props(3), 0.0d0)) * (dev_e - eps_v_new)))

      DO ii = 1, 3
        DO jj = 1, 3
          sigma_new(ii,jj) = sigma_new(ii,jj)
        END DO
      END DO

      RETURN
      END SUBROUTINE smallstrainviscoelastic_stress_update

