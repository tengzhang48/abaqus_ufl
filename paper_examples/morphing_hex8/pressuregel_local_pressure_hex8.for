C     Fields: global u, mu; local p stored in SVARS(1)
C     Element: Hex8, NDOFEL = 32
C======================================================================
      MODULE localp_uvarm_bridge
      IMPLICIT NONE
      INTEGER, PARAMETER :: LOCALP_UVARM_OFFSET = 10000
      INTEGER, PARAMETER :: LOCALP_MAX_GP = 64
      INTEGER, PARAMETER :: LOCALP_NUVAR = 2
      DOUBLE PRECISION, ALLOCATABLE :: LOCALP_UVAR(:,:,:)
      CONTAINS
      SUBROUTINE localp_ensure_capacity(noel)
      IMPLICIT NONE
      INTEGER, INTENT(IN) :: noel
      INTEGER :: oldn, newn
      DOUBLE PRECISION, ALLOCATABLE :: tmp(:,:,:)
      IF (noel .LE. 0) RETURN
      IF (.NOT. ALLOCATED(LOCALP_UVAR)) THEN
        newn = MAX(1024, noel)
        ALLOCATE(LOCALP_UVAR(newn,LOCALP_MAX_GP,LOCALP_NUVAR))
        LOCALP_UVAR = 0.0d0
      ELSE IF (noel .GT. SIZE(LOCALP_UVAR,1)) THEN
        oldn = SIZE(LOCALP_UVAR,1)
        newn = MAX(noel, 2*oldn)
        ALLOCATE(tmp(oldn,LOCALP_MAX_GP,LOCALP_NUVAR))
        tmp = LOCALP_UVAR
        DEALLOCATE(LOCALP_UVAR)
        ALLOCATE(LOCALP_UVAR(newn,LOCALP_MAX_GP,LOCALP_NUVAR))
        LOCALP_UVAR = 0.0d0
        LOCALP_UVAR(1:oldn,:,:) = tmp
        DEALLOCATE(tmp)
      END IF
      RETURN
      END SUBROUTINE localp_ensure_capacity

      SUBROUTINE localp_store_uvarm(noel, npt, phi, p)
      IMPLICIT NONE
      INTEGER, INTENT(IN) :: noel, npt
      DOUBLE PRECISION, INTENT(IN) :: phi, p
      IF (npt .LT. 1 .OR. npt .GT. LOCALP_MAX_GP) RETURN
      CALL localp_ensure_capacity(noel)
      LOCALP_UVAR(noel,npt,1) = phi
      LOCALP_UVAR(noel,npt,2) = p
      RETURN
      END SUBROUTINE localp_store_uvarm

      SUBROUTINE localp_fetch_uvarm(noel, npt, uvar, nuvar)
      IMPLICIT NONE
      INTEGER, INTENT(IN) :: noel, npt, nuvar
      DOUBLE PRECISION, INTENT(OUT) :: uvar(nuvar)
      INTEGER :: src, i
      DO i = 1, nuvar
        uvar(i) = 0.0d0
      END DO
      src = noel - LOCALP_UVARM_OFFSET
      IF (.NOT. ALLOCATED(LOCALP_UVAR)) RETURN
      IF (src .LT. 1 .OR. src .GT. SIZE(LOCALP_UVAR,1)) RETURN
      IF (npt .LT. 1 .OR. npt .GT. LOCALP_MAX_GP) RETURN
      DO i = 1, MIN(nuvar, LOCALP_NUVAR)
        uvar(i) = LOCALP_UVAR(src,npt,i)
      END DO
      RETURN
      END SUBROUTINE localp_fetch_uvarm
      END MODULE localp_uvarm_bridge

