C======================================================================
C     UEL residual and tangent
C======================================================================
      SUBROUTINE UEL(RHS, AMATRX, SVARS, ENERGY, NDOFEL,
     &  NRHS, NSVARS, PROPS, NPROPS, COORDS, MCRD, NNODE,
     &  U, DU, V, A, JTYPE, TIME, DTIME, KSTEP, KINC,
     &  JELEM, PARAMS, NDLOAD, JDLTYP, ADLMAG, PREDEF,
     &  NPREDF, LFLAGS, MLVARX, DDLMAG, MDLOAD, PNEWDT,
     &  JPROPS, NJPROP, PERIOD)
      USE localp_uvarm_bridge
      IMPLICIT NONE
      INTEGER NDOFEL, NRHS, NSVARS, NPROPS, MCRD, NNODE
      INTEGER JTYPE, KSTEP, KINC, JELEM, NDLOAD, NPREDF
      INTEGER MLVARX, MDLOAD, NJPROP
      INTEGER JDLTYP(MDLOAD,*), LFLAGS(*), JPROPS(*)
      DOUBLE PRECISION RHS(MLVARX,*), AMATRX(NDOFEL,NDOFEL)
      DOUBLE PRECISION SVARS(NSVARS), ENERGY(8)
      DOUBLE PRECISION PROPS(NPROPS), COORDS(MCRD,NNODE)
      DOUBLE PRECISION U(NDOFEL), DU(MLVARX,*), V(NDOFEL), A(NDOFEL)
      DOUBLE PRECISION TIME(2), DTIME, PARAMS(3)
      DOUBLE PRECISION ADLMAG(MDLOAD,*), PREDEF(2,NPREDF,NNODE)
      DOUBLE PRECISION DDLMAG(MDLOAD,*), PNEWDT, PERIOD
      INTEGER, PARAMETER :: ndim = 3, NNODE_E = 8, NGP = 8
      DOUBLE PRECISION :: u_node(ndim,NNODE_E), u_old(ndim,NNODE_E)
      DOUBLE PRECISION :: mu_node(NNODE_E), mu_old(NNODE_E)
      INTEGER :: edof_u(ndim,NNODE_E), edof_mu(NNODE_E)
      DOUBLE PRECISION :: coords2(ndim,NNODE_E)
      DOUBLE PRECISION :: sh4(NNODE_E), dshxi4(NNODE_E,ndim)
      DOUBLE PRECISION :: dsh4(NNODE_E,ndim), xi_gp(NGP,ndim), w_gp(NGP)
      DOUBLE PRECISION :: detJ, Jinv(ndim,ndim), wdetJ, dt_safe
      DOUBLE PRECISION :: F(3,3), F_old(3,3), grad_mu(3)
      DOUBLE PRECISION :: mu_gp, p_elem, p_old, R_p, K_pp, dp
      DOUBLE PRECISION :: detF_diag, Je_diag, phi_diag, det33d
      DOUBLE PRECISION :: P_real(3,3), rp_real, jR_real(3), cdot_real
      DOUBLE PRECISION :: dP_dF(3,3,3,3), dP_dp(3,3)
      DOUBLE PRECISION :: drp_dF(3,3), drp_dp, drp_dmu
      DOUBLE PRECISION :: dflux_dF(3,3,3), dflux_dp(3)
      DOUBLE PRECISION :: dflux_dmu(3), dflux_dgrad_mu(3,3)
      DOUBLE PRECISION :: dstorage_dF(3,3), dstorage_dp
      DOUBLE PRECISION :: Kxp(NDOFEL), Kpx(NDOFEL), Rtmp(NDOFEL)
      DOUBLE PRECISION :: Kxx(NDOFEL,NDOFEL), Rp_final
      INTEGER :: ngp_out, stat, idx, ii_v, jj_v
      INTEGER :: i, j, k, l, kk, iter_p, row, col
      INTEGER :: conv_p

      DO ii_v = 1, NNODE_E
        DO i = 1, ndim
          coords2(i,ii_v) = COORDS(i,ii_v)
        END DO
      END DO
      DO i = 1, NDOFEL
        RHS(i,1) = 0.0d0
        Rtmp(i) = 0.0d0
        Kxp(i) = 0.0d0
        Kpx(i) = 0.0d0
        DO j = 1, NDOFEL
          AMATRX(i,j) = 0.0d0
          Kxx(i,j) = 0.0d0
        END DO
      END DO
      IF (NRHS .GE. 2) THEN
        DO i = 1, NDOFEL
          RHS(i,2) = 0.0d0
        END DO
      END IF

C     Procedure dispatch (Abaqus UEL contract): supported are the
C     static/quasi-static and coupled thermal-stress procedures
C     (LFLAGS(1)=1,2,71,72,73), general non-perturbation steps
C     (LFLAGS(4)=0), NRHS=1 (modified Riks is not implemented),
C     and request types LFLAGS(3)=1,2,5. Types 2 and 5 receive
C     the full residual+stiffness evaluation, a superset of the
C     requested output; the unused array is ignored by Abaqus.
C     Every other request returns the zeroed arrays.
      IF (LFLAGS(1) .NE. 1 .AND. LFLAGS(1) .NE. 2 .AND.
     &    LFLAGS(1) .NE. 71 .AND. LFLAGS(1) .NE. 72 .AND.
     &    LFLAGS(1) .NE. 73) THEN
        RETURN
      END IF
      IF (LFLAGS(4) .NE. 0) THEN
        RETURN
      END IF
      IF (NRHS .GE. 2) THEN
        RETURN
      END IF
      IF (LFLAGS(3) .NE. 1 .AND. LFLAGS(3) .NE. 2 .AND.
     &    LFLAGS(3) .NE. 5) THEN
        RETURN
      END IF

      dt_safe = DTIME
      IF (dt_safe .LT. 1.0d-14) dt_safe = 1.0d-14

      idx = 0
      DO ii_v = 1, NNODE_E
        DO i = 1, ndim
          idx = idx + 1
          u_node(i,ii_v) = U(idx)
          u_old(i,ii_v) = U(idx) - DU(idx,1)
          edof_u(i,ii_v) = idx
        END DO
        idx = idx + 1
        mu_node(ii_v) = U(idx)
        mu_old(ii_v) = U(idx) - DU(idx,1)
        edof_mu(ii_v) = idx
      END DO

      p_old = 0.0d0
      IF (NSVARS .GE. 1) p_old = SVARS(1)
      p_elem = p_old
      CALL gauss_hex8(xi_gp, w_gp, ngp_out)

C     Local Newton for element pressure
      conv_p = 0
      DO iter_p = 1, 25
        R_p = 0.0d0
        K_pp = 0.0d0
        DO kk = 1, ngp_out
          CALL shape_hex8(xi_gp(kk,1), xi_gp(kk,2), xi_gp(kk,3),
     &      sh4, dshxi4)
          CALL map_grad_3d(dshxi4, coords2, NNODE_E, dsh4,
     &      detJ, Jinv, stat)
          IF (stat .EQ. 0) THEN
            PNEWDT = 0.25d0
            RETURN
          END IF
          wdetJ = detJ * w_gp(kk)
          CALL eye33d(F)
          CALL eye33d(F_old)
          mu_gp = 0.0d0
          grad_mu(1) = 0.0d0
          grad_mu(2) = 0.0d0
          grad_mu(3) = 0.0d0
          DO ii_v = 1, NNODE_E
            mu_gp = mu_gp + mu_node(ii_v)*sh4(ii_v)
            DO i = 1, ndim
              grad_mu(i) = grad_mu(i)
     &          + mu_node(ii_v)*dsh4(ii_v,i)
              DO j = 1, ndim
                F(i,j) = F(i,j)
     &            + u_node(i,ii_v)*dsh4(ii_v,j)
                F_old(i,j) = F_old(i,j)
     &            + u_old(i,ii_v)*dsh4(ii_v,j)
              END DO
            END DO
          END DO
          IF (det33d(F) .LE. 0.0d0) THEN
            PNEWDT = 0.25d0
            RETURN
          END IF
          CALL localp_eval_tangents(F, p_elem, mu_gp,
     &      grad_mu, F_old, p_old, PROPS, dt_safe,
     &      P_real, rp_real, jR_real, cdot_real,
     &      dP_dF, dP_dp, drp_dF, drp_dp, drp_dmu,
     &      dflux_dF, dflux_dp, dflux_dmu,
     &      dflux_dgrad_mu, dstorage_dF, dstorage_dp)
          R_p = R_p + rp_real*wdetJ
          K_pp = K_pp + drp_dp*wdetJ
        END DO
        IF (DABS(K_pp) .LT. 1.0d-30) THEN
          PNEWDT = 0.25d0
          RETURN
        END IF
        IF (R_p .NE. R_p .OR. K_pp .NE. K_pp .OR.
     &      DABS(R_p) .GT. 1.0d30 .OR.
     &      DABS(K_pp) .GT. 1.0d30) THEN
          PNEWDT = 0.25d0
          RETURN
        END IF
        dp = -R_p / K_pp
        p_elem = p_elem + dp
        IF (DABS(R_p) .LT. 1.0d-10) THEN
          conv_p = 1
          EXIT
        END IF
        IF (DABS(dp) .LT. 1.0d-10*(1.0d0+DABS(p_elem))) THEN
          conv_p = 1
          EXIT
        END IF
      END DO
C     Unconverged local solve: request a smaller increment,
C     matching the global solver response to non-convergence.
      IF (conv_p .EQ. 0) THEN
        PNEWDT = 0.25d0
        RETURN
      END IF

C     Assemble full x-p blocks, x = [u, mu]
      R_p = 0.0d0
      K_pp = 0.0d0
      DO kk = 1, ngp_out
        CALL shape_hex8(xi_gp(kk,1), xi_gp(kk,2), xi_gp(kk,3), sh4,
     &dshxi4)
        CALL map_grad_3d(dshxi4, coords2, NNODE_E, dsh4, detJ,
     &    Jinv, stat)
        IF (stat .EQ. 0) THEN
          PNEWDT = 0.25d0
          RETURN
        END IF
        wdetJ = detJ * w_gp(kk)
        CALL eye33d(F)
        CALL eye33d(F_old)
        mu_gp = 0.0d0
        grad_mu(1) = 0.0d0
        grad_mu(2) = 0.0d0
        grad_mu(3) = 0.0d0
        DO ii_v = 1, NNODE_E
          mu_gp = mu_gp + mu_node(ii_v)*sh4(ii_v)
          DO i = 1, ndim
            grad_mu(i) = grad_mu(i)
     &        + mu_node(ii_v)*dsh4(ii_v,i)
            DO j = 1, ndim
              F(i,j) = F(i,j)
     &          + u_node(i,ii_v)*dsh4(ii_v,j)
              F_old(i,j) = F_old(i,j)
     &          + u_old(i,ii_v)*dsh4(ii_v,j)
            END DO
          END DO
        END DO
        IF (det33d(F) .LE. 0.0d0) THEN
          PNEWDT = 0.25d0
          RETURN
        END IF
        CALL localp_eval_tangents(F, p_elem, mu_gp, grad_mu,
     &    F_old, p_old, PROPS, dt_safe,
     &    P_real, rp_real, jR_real, cdot_real,
     &    dP_dF, dP_dp, drp_dF, drp_dp, drp_dmu,
     &    dflux_dF, dflux_dp, dflux_dmu,
     &    dflux_dgrad_mu, dstorage_dF, dstorage_dp)
        detF_diag = det33d(F)
        Je_diag = DEXP(p_elem / PROPS(2))
        phi_diag = 0.0d0
        IF (NPROPS .GE. 9 .AND. DABS(detF_diag) .GT. 1.0d-30)
     &    phi_diag = PROPS(9) * Je_diag / detF_diag
        CALL localp_store_uvarm(JELEM, kk, phi_diag, p_elem)
        IF (LFLAGS(3) .EQ. 1 .AND. NSVARS .GE. 1 + NGP)
     &    SVARS(1+kk) = phi_diag
        IF (LFLAGS(3) .EQ. 1 .AND. NSVARS .GE. 1 + 2*NGP)
     &    SVARS(1+NGP+kk) = p_elem
        R_p = R_p + rp_real*wdetJ
        K_pp = K_pp + drp_dp*wdetJ

        DO ii_v = 1, NNODE_E
          DO i = 1, ndim
            row = edof_u(i,ii_v)
            DO j = 1, ndim
              Rtmp(row) = Rtmp(row)
     &          - P_real(i,j)*dsh4(ii_v,j)*wdetJ
            END DO
          END DO
          row = edof_mu(ii_v)
          Rtmp(row) = Rtmp(row) - cdot_real*sh4(ii_v)*wdetJ
          DO j = 1, ndim
            Rtmp(row) = Rtmp(row)
     &        + jR_real(j)*dsh4(ii_v,j)*wdetJ
          END DO
        END DO
        DO ii_v = 1, NNODE_E
          DO i = 1, ndim
            row = edof_u(i,ii_v)
            DO j = 1, ndim
              Kxp(row) = Kxp(row)
     &          + dP_dp(i,j)*dsh4(ii_v,j)*wdetJ
            END DO
          END DO
          row = edof_mu(ii_v)
          Kxp(row) = Kxp(row) + dstorage_dp*sh4(ii_v)*wdetJ
          DO j = 1, ndim
            Kxp(row) = Kxp(row)
     &        - dflux_dp(j)*dsh4(ii_v,j)*wdetJ
          END DO
          col = edof_mu(ii_v)
          Kpx(col) = Kpx(col) + drp_dmu*sh4(ii_v)*wdetJ
          DO k = 1, ndim
            col = edof_u(k,ii_v)
            DO l = 1, ndim
              Kpx(col) = Kpx(col)
     &          + drp_dF(k,l)*dsh4(ii_v,l)*wdetJ
            END DO
          END DO
        END DO
        DO ii_v = 1, NNODE_E
          DO jj_v = 1, NNODE_E
            DO i = 1, ndim
              row = edof_u(i,ii_v)
              DO k = 1, ndim
                col = edof_u(k,jj_v)
                DO j = 1, ndim
                  DO l = 1, ndim
                    Kxx(row,col) = Kxx(row,col)
     &                + dP_dF(i,j,k,l)
     &                * dsh4(ii_v,j)*dsh4(jj_v,l)*wdetJ
                  END DO
                END DO
              END DO
              col = edof_mu(jj_v)
C             dP/dmu = 0 for this gel
            END DO
            row = edof_mu(ii_v)
            DO k = 1, ndim
              col = edof_u(k,jj_v)
              DO l = 1, ndim
                Kxx(row,col) = Kxx(row,col)
     &            + dstorage_dF(k,l)*sh4(ii_v)
     &            * dsh4(jj_v,l)*wdetJ
                DO j = 1, ndim
                  Kxx(row,col) = Kxx(row,col)
     &              - dflux_dF(j,k,l)*dsh4(ii_v,j)
     &              * dsh4(jj_v,l)*wdetJ
                END DO
              END DO
            END DO
            col = edof_mu(jj_v)
C           storage has no d/dmu term
            DO j = 1, ndim
              Kxx(row,col) = Kxx(row,col)
     &          - dflux_dmu(j)*dsh4(ii_v,j)*sh4(jj_v)*wdetJ
              DO l = 1, ndim
                Kxx(row,col) = Kxx(row,col)
     &            - dflux_dgrad_mu(j,l)*dsh4(ii_v,j)
     &            * dsh4(jj_v,l)*wdetJ
              END DO
            END DO
          END DO
        END DO
      END DO

      IF (DABS(K_pp) .LT. 1.0d-30) THEN
        PNEWDT = 0.25d0
        RETURN
      END IF
      Rp_final = R_p
      DO i = 1, NDOFEL
        RHS(i,1) = Rtmp(i) + Kxp(i)*Rp_final/K_pp
        DO j = 1, NDOFEL
          AMATRX(i,j) = Kxx(i,j) - Kxp(i)*Kpx(j)/K_pp
        END DO
      END DO
      IF (LFLAGS(3) .EQ. 1 .AND. NSVARS .GE. 1)
     &  SVARS(1) = p_elem
C     Optional diagnostic layouts.
C     Preserve solver state in SVARS(1).  If enough slots exist,
C     store UVARM-like diagnostics by integration point:
C       SVARS(1+i)       = phi at GP i
C       SVARS(1+NGP+i)   = local pressure at GP i
      IF (LFLAGS(3) .EQ. 1 .AND. ndim .EQ. 2
     &    .AND. NSVARS .GE. 32) THEN
        SVARS(1) = p_elem
        SVARS(9) = p_elem
        SVARS(17) = p_elem
        SVARS(25) = p_elem
      END IF
      RETURN
      END SUBROUTINE UEL

