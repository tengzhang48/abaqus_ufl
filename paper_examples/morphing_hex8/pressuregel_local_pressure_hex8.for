      SUBROUTINE pressuregel_stress_PK1(F, p, mu, props, P_out)
      IMPLICIT NONE
      DOUBLE COMPLEX, INTENT(IN) :: F(3,3)
      DOUBLE COMPLEX, INTENT(IN) :: p
      DOUBLE COMPLEX, INTENT(IN) :: mu
      DOUBLE PRECISION, INTENT(IN) :: props(9)
      DOUBLE COMPLEX, INTENT(OUT) :: P_out(3,3)

      DOUBLE COMPLEX :: det33z
      DOUBLE COMPLEX :: INV1(3,3)
      DOUBLE COMPLEX :: AT2(3,3)
      DOUBLE COMPLEX :: INV3(3,3)
      DOUBLE COMPLEX :: AT4(3,3)
      INTEGER :: ii, jj

      CALL inv33z(F, INV1)
      CALL transpose33z(INV1, AT2)
      CALL inv33z(F, INV3)
      CALL transpose33z(INV3, AT4)

      DO ii = 1, 3
        DO jj = 1, 3
          P_out(ii,jj) = ((DCMPLX(props(1), 0.0d0) * (F(ii,jj) - AT2(ii,
     &jj))) + (p * AT4(ii,jj)))
        END DO
      END DO

      RETURN
      END SUBROUTINE pressuregel_stress_PK1

      SUBROUTINE pressuregel_pressure_resid(F, p, mu, props, rp_out)
      IMPLICIT NONE
      DOUBLE COMPLEX, INTENT(IN) :: F(3,3)
      DOUBLE COMPLEX, INTENT(IN) :: p
      DOUBLE COMPLEX, INTENT(IN) :: mu
      DOUBLE PRECISION, INTENT(IN) :: props(9)
      DOUBLE COMPLEX, INTENT(OUT) :: rp_out

      DOUBLE COMPLEX :: det33z
      DOUBLE COMPLEX :: J
      DOUBLE COMPLEX :: Je
      DOUBLE COMPLEX :: phi

      J = det33z(F)
      Je = EXP((p / DCMPLX(props(2), 0.0d0)))
      phi = ((DCMPLX(props(9), 0.0d0) * Je) / J)
      rp_out = (((mu - DCMPLX(props(5), 0.0d0)) - ((DCMPLX(props(7),
     &0.0d0) * DCMPLX(props(8), 0.0d0)) *
     &((LOG((DCMPLX(1.000000000000000d+00, 0.0d0) - phi)) + phi) +
     &(DCMPLX(props(3), 0.0d0) * (phi ** DCMPLX(2.0d0, 0.0d0)))))) +
     &(((phi / DCMPLX(props(9), 0.0d0)) * DCMPLX(props(6), 0.0d0)) * p))

      RETURN
      END SUBROUTINE pressuregel_pressure_resid

      SUBROUTINE pressuregel_solvent_flux(F, p, mu, grad_mu, props,
     &jR_out)
      IMPLICIT NONE
      DOUBLE COMPLEX, INTENT(IN) :: F(3,3)
      DOUBLE COMPLEX, INTENT(IN) :: p
      DOUBLE COMPLEX, INTENT(IN) :: mu
      DOUBLE COMPLEX, INTENT(IN) :: grad_mu(3)
      DOUBLE PRECISION, INTENT(IN) :: props(9)
      DOUBLE COMPLEX, INTENT(OUT) :: jR_out(3)

      DOUBLE COMPLEX :: det33z
      DOUBLE COMPLEX :: AT1(3,3)
      DOUBLE COMPLEX :: MM2(3,3)
      DOUBLE COMPLEX :: INV3(3,3)
      DOUBLE COMPLEX :: Cinv(3,3)
      DOUBLE COMPLEX :: MM4(3)
      DOUBLE COMPLEX :: J
      DOUBLE COMPLEX :: Je
      DOUBLE COMPLEX :: phi
      DOUBLE COMPLEX :: cR0
      DOUBLE COMPLEX :: cR
      DOUBLE COMPLEX :: M
      INTEGER :: ii, jj

      J = det33z(F)
      Je = EXP((p / DCMPLX(props(2), 0.0d0)))
      phi = ((DCMPLX(props(9), 0.0d0) * Je) / J)
      CALL transpose33z(F, AT1)
      CALL matmul33z(AT1, F, MM2)
      CALL inv33z(MM2, INV3)
      Cinv = INV3
      cR0 = ((DCMPLX(1.000000000000000d+00, 0.0d0) - DCMPLX(props(9),
     &0.0d0)) / DCMPLX(props(6), 0.0d0))
      cR = (cR0 + ((DCMPLX(props(9), 0.0d0) - phi) / (DCMPLX(props(6),
     &0.0d0) * phi)))
      M = ((DCMPLX(props(4), 0.0d0) * cR) / (DCMPLX(props(7), 0.0d0) *
     &DCMPLX(props(8), 0.0d0)))
      CALL matvec33z(Cinv, grad_mu, MM4)

      DO ii = 1, 3
        jR_out(ii) = ((-M) * MM4(ii))
      END DO

      RETURN
      END SUBROUTINE pressuregel_solvent_flux

      SUBROUTINE pressuregel_solvent_storage(F, F_old, p, p_old, dt,
     &props, cdot_out)
      IMPLICIT NONE
      DOUBLE COMPLEX, INTENT(IN) :: F(3,3)
      DOUBLE COMPLEX, INTENT(IN) :: F_old(3,3)
      DOUBLE COMPLEX, INTENT(IN) :: p
      DOUBLE COMPLEX, INTENT(IN) :: p_old
      DOUBLE PRECISION, INTENT(IN) :: dt
      DOUBLE PRECISION, INTENT(IN) :: props(9)
      DOUBLE COMPLEX, INTENT(OUT) :: cdot_out

      DOUBLE COMPLEX :: det33z
      DOUBLE COMPLEX :: J
      DOUBLE COMPLEX :: J_old
      DOUBLE COMPLEX :: Je
      DOUBLE COMPLEX :: Je_old

      J = det33z(F)
      J_old = det33z(F_old)
      Je = EXP((p / DCMPLX(props(2), 0.0d0)))
      Je_old = EXP((p_old / DCMPLX(props(2), 0.0d0)))
      cdot_out = (((J / Je) - (J_old / Je_old)) / (DCMPLX(props(6),
     &0.0d0) * dt))

      RETURN
      END SUBROUTINE pressuregel_solvent_storage


C======================================================================
C     Local-pressure tangent engine
C======================================================================
      SUBROUTINE localp_eval_tangents(
     &  F, p, mu, grad_mu, F_old, p_old, PROPS, dt,
     &  P_real, rp_real, jR_real, cdot_real,
     &  dP_dF, dP_dp, drp_dF, drp_dp, drp_dmu,
     &  dflux_dF, dflux_dp, dflux_dmu, dflux_dgrad_mu,
     &  dstorage_dF, dstorage_dp)
      IMPLICIT NONE
      DOUBLE PRECISION, INTENT(IN) :: F(3,3), p, mu
      DOUBLE PRECISION, INTENT(IN) :: grad_mu(3)
      DOUBLE PRECISION, INTENT(IN) :: F_old(3,3), p_old
      DOUBLE PRECISION, INTENT(IN) :: PROPS(9), dt
      DOUBLE PRECISION, INTENT(OUT) :: P_real(3,3)
      DOUBLE PRECISION, INTENT(OUT) :: rp_real, jR_real(3)
      DOUBLE PRECISION, INTENT(OUT) :: cdot_real
      DOUBLE PRECISION, INTENT(OUT) :: dP_dF(3,3,3,3)
      DOUBLE PRECISION, INTENT(OUT) :: dP_dp(3,3)
      DOUBLE PRECISION, INTENT(OUT) :: drp_dF(3,3)
      DOUBLE PRECISION, INTENT(OUT) :: drp_dp, drp_dmu
      DOUBLE PRECISION, INTENT(OUT) :: dflux_dF(3,3,3)
      DOUBLE PRECISION, INTENT(OUT) :: dflux_dp(3)
      DOUBLE PRECISION, INTENT(OUT) :: dflux_dmu(3)
      DOUBLE PRECISION, INTENT(OUT) :: dflux_dgrad_mu(3,3)
      DOUBLE PRECISION, INTENT(OUT) :: dstorage_dF(3,3)
      DOUBLE PRECISION, INTENT(OUT) :: dstorage_dp
      DOUBLE PRECISION, PARAMETER :: CS_H = 1.0d-10
      DOUBLE COMPLEX :: Fz(3,3), F_old_z(3,3)
      DOUBLE COMPLEX :: p_scalar_z, muz, grad_mu_z(3), p_old_z
      DOUBLE COMPLEX :: stress_z(3,3), rp_z, flux_z(3), cdot_z
      INTEGER :: i, j, k, l

C     Real outputs
      CALL real2complex33(F, Fz)
      CALL real2complex33(F_old, F_old_z)
      p_scalar_z = DCMPLX(p, 0.0d0)
      muz = DCMPLX(mu, 0.0d0)
      p_old_z = DCMPLX(p_old, 0.0d0)
      CALL real2complex3(grad_mu, grad_mu_z)
      CALL pressuregel_stress_PK1(Fz, p_scalar_z, muz, PROPS, stress_z)
      CALL pressuregel_pressure_resid(Fz, p_scalar_z, muz, PROPS, rp_z)
      CALL pressuregel_solvent_flux(Fz, p_scalar_z, muz, grad_mu_z,
     &PROPS, flux_z)
      CALL pressuregel_solvent_storage(Fz, F_old_z, p_scalar_z, p_old_z,
     & dt, PROPS, cdot_z)
      DO i = 1, 3
        jR_real(i) = DBLE(flux_z(i))
        DO j = 1, 3
          P_real(i,j) = DBLE(stress_z(i,j))
        END DO
      END DO
      rp_real = DBLE(rp_z)
      cdot_real = DBLE(cdot_z)

C     F perturbations
      DO k = 1, 3
        DO l = 1, 3
          CALL real2complex33(F, Fz)
          CALL real2complex33(F_old, F_old_z)
          p_scalar_z = DCMPLX(p, 0.0d0)
          muz = DCMPLX(mu, 0.0d0)
          p_old_z = DCMPLX(p_old, 0.0d0)
          CALL real2complex3(grad_mu, grad_mu_z)
          Fz(k,l) = Fz(k,l) + DCMPLX(0.0d0, CS_H)
          CALL pressuregel_stress_PK1(Fz, p_scalar_z, muz, PROPS,
     &stress_z)
          CALL pressuregel_pressure_resid(Fz, p_scalar_z, muz, PROPS,
     &rp_z)
          CALL pressuregel_solvent_flux(Fz, p_scalar_z, muz, grad_mu_z,
     &PROPS, flux_z)
          CALL pressuregel_solvent_storage(Fz, F_old_z, p_scalar_z,
     &p_old_z, dt, PROPS, cdot_z)
          DO i = 1, 3
            dflux_dF(i,k,l) = AIMAG(flux_z(i)) / CS_H
            DO j = 1, 3
              dP_dF(i,j,k,l) = AIMAG(stress_z(i,j)) / CS_H
            END DO
          END DO
          drp_dF(k,l) = AIMAG(rp_z) / CS_H
          dstorage_dF(k,l) = AIMAG(cdot_z) / CS_H
        END DO
      END DO

C     p perturbation
      CALL real2complex33(F, Fz)
      CALL real2complex33(F_old, F_old_z)
      p_scalar_z = DCMPLX(p, CS_H)
      muz = DCMPLX(mu, 0.0d0)
      p_old_z = DCMPLX(p_old, 0.0d0)
      CALL real2complex3(grad_mu, grad_mu_z)
      CALL pressuregel_stress_PK1(Fz, p_scalar_z, muz, PROPS, stress_z)
      CALL pressuregel_pressure_resid(Fz, p_scalar_z, muz, PROPS, rp_z)
      CALL pressuregel_solvent_flux(Fz, p_scalar_z, muz, grad_mu_z,
     &PROPS, flux_z)
      CALL pressuregel_solvent_storage(Fz, F_old_z, p_scalar_z, p_old_z,
     & dt, PROPS, cdot_z)
      DO i = 1, 3
        dflux_dp(i) = AIMAG(flux_z(i)) / CS_H
        DO j = 1, 3
          dP_dp(i,j) = AIMAG(stress_z(i,j)) / CS_H
        END DO
      END DO
      drp_dp = AIMAG(rp_z) / CS_H
      dstorage_dp = AIMAG(cdot_z) / CS_H

C     mu perturbation
      CALL real2complex33(F, Fz)
      CALL real2complex33(F_old, F_old_z)
      p_scalar_z = DCMPLX(p, 0.0d0)
      muz = DCMPLX(mu, CS_H)
      p_old_z = DCMPLX(p_old, 0.0d0)
      CALL real2complex3(grad_mu, grad_mu_z)
      CALL pressuregel_pressure_resid(Fz, p_scalar_z, muz, PROPS, rp_z)
      CALL pressuregel_solvent_flux(Fz, p_scalar_z, muz, grad_mu_z,
     &PROPS, flux_z)
      drp_dmu = AIMAG(rp_z) / CS_H
      DO i = 1, 3
        dflux_dmu(i) = AIMAG(flux_z(i)) / CS_H
      END DO

C     grad(mu) perturbations
      DO k = 1, 3
        CALL real2complex33(F, Fz)
        p_scalar_z = DCMPLX(p, 0.0d0)
        muz = DCMPLX(mu, 0.0d0)
        CALL real2complex3(grad_mu, grad_mu_z)
        grad_mu_z(k) = grad_mu_z(k)
     &    + DCMPLX(0.0d0, CS_H)
        CALL pressuregel_solvent_flux(Fz, p_scalar_z, muz, grad_mu_z,
     &PROPS, flux_z)
        DO i = 1, 3
          dflux_dgrad_mu(i,k) = AIMAG(flux_z(i)) / CS_H
        END DO
      END DO

      RETURN
      END SUBROUTINE localp_eval_tangents

